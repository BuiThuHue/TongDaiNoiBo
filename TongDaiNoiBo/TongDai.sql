CREATE DATABASE Quan_ly_ban_hang;
USE Quan_ly_ban_hang;

CREATE TABLE HANG_HOA (
    MaHang INT AUTO_INCREMENT PRIMARY KEY,
    TenHang VARCHAR(100) NOT NULL,
    DonGiaNhap INT NOT NULL,
    DonGiaBan INT NOT NULL
);

CREATE TABLE KHACH_HANG (
    MaKhach INT AUTO_INCREMENT PRIMARY KEY,
    TenKhach VARCHAR(100) NOT NULL,
    DienThoai VARCHAR(11) NOT NULL
);

CREATE TABLE HOA_DON (
    SoHD INT AUTO_INCREMENT PRIMARY KEY,
    MaKhach INT NOT NULL,
    MaHang INT NOT NULL,
    SoLuong INT NOT NULL,
    NgayLapHD DATE NOT NULL,

    FOREIGN KEY (MaKhach) REFERENCES KHACH_HANG(MaKhach),
    FOREIGN KEY (MaHang) REFERENCES HANG_HOA(MaHang)
);

